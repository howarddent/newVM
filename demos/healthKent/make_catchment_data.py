# Generates catchmentdata.inc for the healthKent demo: East Kent Hospitals
# University NHS Foundation Trust's (RVV) catchment population by LSOA, for
# the memo's "East Kent with two or three A&Es" section.
#
# Source: OHID, "NHS acute (hospital) trust catchment populations", April 2026
# (OGL v3), Table 4 (emergency admissions), catchment year 2024 (HES 2022-23
# to 2024-25, ONS mid-2022 populations):
#   https://www.gov.uk/government/statistics/nhs-acute-hospital-trust-catchment-populations-april-2026
#   data tables: nhs-acute-hospital-trust-catchment-populations-data_tables-april-2026.ods
# Convert the ODS's sheets to CSV first (it is 550 MB of XML unpacked):
#   soffice --headless --convert-to 'csv:Text - txt - csv (StarCalc):44,34,UTF8,1,,0,false,true,false,false,false,-1' <file>.ods
# and pass the "-Emergency.csv" sheet.
#
# Table 4 gives, per trust and MSOA, the trust's catchment population from
# that MSOA ("MSOA total catchment": the share of the MSOA's patients
# admitted to the trust, applied age-sex band by band to its population).
# Here each MSOA's figure is shared between its LSOAs by mid-2024 population
# (kentdata.inc), by name (LSOA "Canterbury 011D" is in MSOA "Canterbury
# 011"); the MSOA names come from ONS's MSOA 2021 names service. The MSOA
# figures sum to 3 % less than the trust's published total (residents with
# no usable MSOA), so everything is scaled to the total, as the trust total
# is the published figure. MSOAs outside Kent and Medway are summed into
# EkCatchOutside.
#
# Usage: python3 make_catchment_data.py <...-Emergency.csv>
# ---------------------------------------------------------------------------
import sys, os, re, csv, json, urllib.request, urllib.parse
from collections import defaultdict

here = os.path.dirname(os.path.abspath(__file__))
TRUST, YEAR = 'RVV', '2024'
NAMES_URL = ('https://services1.arcgis.com/ESMARspQHYMw9BZ9/arcgis/rest/services/'
             'MSOA_DEC_2021_EW_NC_v3/FeatureServer/0/query')


def kent_arr(name, typ):
    s = open(os.path.join(here, 'kentdata.inc')).read()
    m = re.search(name + r': array\[0\.\.(\d+)\] of ' + typ + r' = \((.*?)\);', s, re.S)
    if typ == 'string':
        return [v.replace("''", "'") for v in re.findall(r"'((?:[^']|'')*)'", m.group(2))]
    return [float(v) for v in m.group(2).replace('\n', ' ').split(',')]


def main(path):
    rows, total = [], None
    for i, x in enumerate(csv.reader(open(path))):
        if i >= 3 and x[0] == YEAR and x[2] == TRUST:
            rows.append((x[4], float(x[9])))
            total = float(x[8])
    codes = [m for m, _ in rows]
    names = {}
    for i in range(0, len(codes), 150):
        q = "MSOA21CD IN ('" + "','".join(codes[i:i + 150]) + "')"
        data = urllib.parse.urlencode({'where': q, 'outFields': 'MSOA21CD,MSOA21NM',
                                       'returnGeometry': 'false', 'f': 'json'}).encode()
        for f in json.load(urllib.request.urlopen(NAMES_URL, data))['features']:
            names[f['attributes']['MSOA21CD']] = f['attributes']['MSOA21NM']
    lname = kent_arr('LsoaName', 'string')
    pop = kent_arr('LsoaPop', 'Integer')
    by_msoa = defaultdict(list)
    for i, n in enumerate(lname):
        by_msoa[n[:-1]].append(i)
    scale = total / sum(c for _, c in rows)
    lsoa = [0.0] * len(lname)
    outside = 0.0
    for m, c in rows:
        c *= scale
        idx = by_msoa.get(names.get(m, ''), [])
        if not idx:
            outside += c
            continue
        p = sum(pop[i] for i in idx)
        for i in idx:
            lsoa[i] += c * pop[i] / p
    print('trust total %.0f, in Kent and Medway %.0f, outside %.0f, MSOAs %d (scale %.4f)'
          % (total, sum(lsoa), outside, len(rows), scale))
    with open(os.path.join(here, 'catchmentdata.inc'), 'w') as fh:
        fh.write('// generated by make_catchment_data.py - do not edit\n')
        fh.write('// East Kent Hospitals (RVV) emergency-admissions catchment population by LSOA,\n')
        fh.write('// OHID NHS acute trust catchment populations, April 2026, catchment year 2024 (OGL v3)\n')
        fh.write('const\n')
        fh.write('  EkCatchYear = %s;\n' % YEAR)
        fh.write('  EkCatchTotal = %.0f;      // the trust\'s published catchment\n' % total)
        fh.write('  EkCatchOutside = %.0f;      // of which living outside Kent and Medway\n' % outside)
        fh.write('  LsoaEkCatch: array[0..%d] of Single = (\n' % (len(lsoa) - 1))
        vals = ['%.1f' % v for v in lsoa]
        for i in range(0, len(vals), 10):
            fh.write('    ' + ', '.join(vals[i:i + 10]) + (',\n' if i + 10 < len(vals) else '\n'))
        fh.write('  );\n')


if __name__ == '__main__':
    main(sys.argv[1])
